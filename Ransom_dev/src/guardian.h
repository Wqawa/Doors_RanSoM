// ============================================================================
//  guardian.h
//
//  双进程互相看守。
//
//  主进程启动时会拉起一个**守护进程**（还是同一个 exe，只是带
//  `--guardian <pid> <gen>` 参数）。两个进程互相盯着：
//
//    * 守护盯着主进程：主进程**被强杀**（没有走正常退出流程）时，
//      守护立刻再拉起一个「保活进程」，然后自己跑一遍「没付清」的
//      惩罚演出（jumpscare + 桌面快捷方式进回收站），跑完退出。
//    * 主进程盯着守护：守护意外死了，主进程再拉起一个，不触发惩罚。
//
//  为什么要有「保活进程」：用户想强行结束演出时，第一刀杀主进程，
//  守护会立刻跑惩罚；如果他在惩罚期间又杀守护，那时**保活进程**会
//  接棒再跑一遍。想一次杀干净就得连杀三个进程，而不是杀一个。
//  保活进程跑不了惩罚（惩罚已经被标记跑过了）就只做「临时保活」——
//  占着进程位，然后等主守护正常退出后自己退。
//
//  为什么正常退出时不触发惩罚：主进程退出前会 SetEvent 一个命名事件
//  `Local\RansomDev_Disarm_<pid>`，守护看到它 signaled 就知道
//  「这是正常退出」，不再跑惩罚。
//
//  ---- 一份进程关系图 ----
//
//      [主进程] --启动--> [主守护(gen=0)] --监视主进程-->
//          主进程被杀  --> 主守护写标记 + 拉保活(gen=1) + 跑惩罚 + Disarm 自己 + 退
//                                                   |
//                                                   v
//                                          [保活守护(gen=1)]
//                                          --监视主守护-->
//                                          主守护正常退 --> 保活一并退
//                                          主守护被强杀 --> 标记已写，跳过惩罚，只退
// ============================================================================
#pragma once

#ifndef WIN32_LEAN_AND_MEAN
#define WIN32_LEAN_AND_MEAN
#endif
#include <windows.h>

namespace guardian {

	// ---- 主进程侧 ----

	// 启动守护进程。幂等：已经在跑就什么都不做。
	bool Start(HINSTANCE hInst);

	// 主进程正常退出之前**必须**调一次。告诉守护「我这次是正常退出，
	// 别触发惩罚」。不调的话守护会把主进程的退出当成被强杀，立刻跑惩罚。
	void Disarm();

	// 定期调（主消息循环里挂个定时器就行）。检查守护还活着没有，
	// 死了就重启一个。内部自己限流，不用每帧调。
	void Tick();

	// 退出前清理：把守护的句柄和事件关掉。
	// 一般只调 Disarm + Stop，两个顺序不能反。
	void Stop();

	// ---- 守护进程侧 ----

	// 命令行带了 `--guardian` 吗？
	bool IsGuardianMode();

	// 解析 `--guardian <pid> [generation]`。
	// generation：0 = 主守护（目标死了要跑惩罚，并先拉起一个保活进程）；
	//             1 = 保活守护（只做临时保活，不再递归创建）。
	bool ParseGuardianArgs(int argc, wchar_t** argv, DWORD& targetPid, int& generation);

	// 守护主循环，返回值直接用作进程退出码。
	int RunGuardian(HINSTANCE hInst, DWORD targetPid, int generation);

	// 清掉「惩罚已经跑过」的标记文件。主进程每次**正常启动**时调一次，
	// 免得上一轮遗留的标记把这一轮的惩罚吞掉。
	void ClearPunishMark();

} // namespace guardian